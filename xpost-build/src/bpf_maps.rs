//! Parse `bpf.toml` `[maps.*]` → `bpf_maps.rs` (dual sync/async `init_firmware_maps`).

use std::collections::BTreeMap;
use std::fs;
use std::path::Path;

use anyhow::{Context, Result, bail};

use crate::util::{escape_rust_str, snake_to_pascal};
use crate::{HEAP_SIZE, POOL_RESERVED};

struct MapSpec {
    name: String,
    map_type: String,
    max_entries: usize,
    key_fields: Vec<(String, String)>,
    value_fields: Vec<(String, String)>,
    /// When true: skip `init_firmware_maps` create/register; embedder calls [`register_map`].
    runtime: bool,
}

pub fn generate(manifest_dir: &Path, out_dir: &Path) -> Result<()> {
    let bpf_toml_path = manifest_dir.join("bpf.toml");
    let text = fs::read_to_string(&bpf_toml_path)
        .with_context(|| format!("failed to read {}", bpf_toml_path.display()))?;

    let root: toml::Table = text.parse().with_context(|| "failed to parse bpf.toml")?;

    let maps_table = match root.get("maps").and_then(|v| v.as_table()) {
        Some(t) => t,
        None => {
            let contents = format!(
                "// @generated by xtask — no [maps.*] entries in bpf.toml\n\
                 pub const FIRMWARE_MAP_COUNT: usize = 0;\n\
                 pub const FIRMWARE_HAS_ARRAY: bool = false;\n\
                 pub const FIRMWARE_HAS_HASH: bool = false;\n\
                 pub const FIRMWARE_HAS_DEVMAP: bool = false;\n\
                 pub const FIRMWARE_HAS_PROG_ARRAY: bool = false;\n\
                 pub const FIRMWARE_HAS_RINGBUF: bool = false;\n\
                 pub const SELFTEST_MAP_ID: crate::map::MapIdx = 0;\n\
                 pub const SELFTEST_MAP_TYPE: &str = \"\";\n\
                 pub const SELFTEST_KEY_SIZE: usize = 0;\n\
                 pub const SELFTEST_VALUE_SIZE: usize = 0;\n\
                 {EMPTY_INIT}\n"
            );
            fs::write(out_dir.join("bpf_maps.rs"), contents).context("write bpf_maps.rs")?;
            return Ok(());
        }
    };

    // Stable order for deterministic codegen / ResourceId assignment.
    let maps: BTreeMap<&String, &toml::Value> = maps_table.iter().collect();

    let mut total_estimated: usize = 0;
    let mut map_specs = Vec::new();

    for (name, entry) in maps {
        let table = entry
            .as_table()
            .ok_or_else(|| anyhow::anyhow!("[maps.{name}] must be a table"))?;

        let map_type = table
            .get("map_type")
            .and_then(|v| v.as_str())
            .ok_or_else(|| anyhow::anyhow!("[maps.{name}] missing map_type"))?;
        let max_entries = table
            .get("max_entries")
            .and_then(|v| v.as_integer())
            .ok_or_else(|| anyhow::anyhow!("[maps.{name}] missing max_entries"))?
            as usize;
        let estimated_bytes = table
            .get("estimated_bytes")
            .and_then(|v| v.as_integer())
            .ok_or_else(|| anyhow::anyhow!("[maps.{name}] missing estimated_bytes"))?
            as usize;

        let value_fields = table
            .get("value")
            .and_then(|v| v.as_str())
            .ok_or_else(|| anyhow::anyhow!("[maps.{name}] missing value"))?;
        let value_fields = parse_fields(value_fields, name, "value")?;

        let key_fields = match map_type {
            "BPF_MAP_TYPE_RINGBUF" => Vec::new(),
            _ => {
                let key = table
                    .get("key")
                    .and_then(|v| v.as_str())
                    .ok_or_else(|| anyhow::anyhow!("[maps.{name}] missing key"))?;
                parse_fields(key, name, "key")?
            }
        };

        total_estimated = total_estimated
            .checked_add(estimated_bytes)
            .ok_or_else(|| anyhow::anyhow!("estimated_bytes overflow summing maps"))?;

        map_specs.push(MapSpec {
            name: name.clone(),
            map_type: map_type.to_string(),
            max_entries,
            key_fields,
            value_fields,
            runtime: table
                .get("runtime")
                .and_then(|v| v.as_bool())
                .unwrap_or(false),
        });
    }

    let required = total_estimated
        .checked_add(POOL_RESERVED)
        .ok_or_else(|| anyhow::anyhow!("heap requirement overflow"))?;
    if required > HEAP_SIZE {
        bail!(
            "bpf.toml maps need {required} bytes (estimated={total_estimated} + reserved={POOL_RESERVED}) \
             but XDP_MAP heap is only {HEAP_SIZE} bytes — refuse to compile"
        );
    }

    let mut out = String::new();
    out.push_str("// @generated by xtask from bpf.toml — do not edit\n");
    out.push_str(&format!(
        "// heap check: estimated={total_estimated} + reserved={POOL_RESERVED} <= HEAP_SIZE={HEAP_SIZE}\n"
    ));
    out.push_str(&format!(
        "pub const FIRMWARE_MAP_COUNT: usize = {};\n",
        map_specs.len()
    ));
    out.push_str(&format!(
        "pub const FIRMWARE_HAS_ARRAY: bool = {};\n",
        map_specs.iter().any(|s| s.map_type == "BPF_MAP_TYPE_ARRAY")
    ));
    out.push_str(&format!(
        "pub const FIRMWARE_HAS_HASH: bool = {};\n",
        map_specs.iter().any(|s| s.map_type == "BPF_MAP_TYPE_HASH")
    ));
    out.push_str(&format!(
        "pub const FIRMWARE_HAS_DEVMAP: bool = {};\n",
        map_specs
            .iter()
            .any(|s| s.map_type == "BPF_MAP_TYPE_DEVMAP")
    ));
    out.push_str(&format!(
        "pub const FIRMWARE_HAS_PROG_ARRAY: bool = {};\n",
        map_specs
            .iter()
            .any(|s| s.map_type == "BPF_MAP_TYPE_PROG_ARRAY")
    ));
    out.push_str(&format!(
        "pub const FIRMWARE_HAS_RINGBUF: bool = {};\n",
        map_specs
            .iter()
            .any(|s| s.map_type == "BPF_MAP_TYPE_RINGBUF")
    ));
    out.push_str(&format!(
        "pub const FIRMWARE_HAS_WDT_FEED: bool = {};\n\n",
        map_specs
            .iter()
            .any(|s| s.map_type == "BPF_MAP_TYPE_XPOST_WDT_FEED")
    ));

    if let Some(first) = map_specs.first() {
        let key_size = c_layout_size(&first.key_fields);
        let value_size = c_layout_size(&first.value_fields);
        out.push_str("/// First map in bpf.toml (BTree order) — used by hw-selftest.\n");
        out.push_str("pub const SELFTEST_MAP_ID: crate::map::MapIdx = 0;\n");
        out.push_str(&format!(
            "pub const SELFTEST_MAP_TYPE: &str = \"{}\";\n",
            first.map_type
        ));
        out.push_str(&format!(
            "pub const SELFTEST_KEY_SIZE: usize = {key_size};\n"
        ));
        out.push_str(&format!(
            "pub const SELFTEST_VALUE_SIZE: usize = {value_size};\n\n"
        ));
    }

    for (idx, spec) in map_specs.iter().enumerate() {
        if spec.runtime {
            continue;
        }
        let type_stem = snake_to_pascal(&spec.name);
        let val_ty = format!("{type_stem}Value");
        let id_const = format!("MAP_ID_{}", spec.name.to_ascii_uppercase());
        let key_size = c_layout_size(&spec.key_fields);
        let value_size = c_layout_size(&spec.value_fields);

        out.push_str(&format!(
            "/// MapIdx for maps.{} from bpf.toml\n",
            spec.name
        ));
        out.push_str(&format!("pub const {id_const}: crate::map::MapIdx = {idx};\n"));
        out.push_str(&format!(
            "pub const {}_KEY_SIZE: usize = {key_size};\n",
            id_const
        ));
        out.push_str(&format!(
            "pub const {}_VALUE_SIZE: usize = {value_size};\n",
            id_const
        ));
        out.push_str(&format!(
            "pub const {}_MAX_ENTRIES: usize = {};\n\n",
            id_const, spec.max_entries
        ));

        match spec.map_type.as_str() {
            "BPF_MAP_TYPE_RINGBUF" => {
                emit_struct(&mut out, &val_ty, &spec.value_fields, false);
            }
            "BPF_MAP_TYPE_HASH"
            | "BPF_MAP_TYPE_ARRAY"
            | "BPF_MAP_TYPE_DEVMAP"
            | "BPF_MAP_TYPE_PROG_ARRAY"
            | "BPF_MAP_TYPE_XPOST_WDT_FEED" => {
                let key_ty = format!("{type_stem}Key");
                emit_struct(&mut out, &key_ty, &spec.key_fields, true);
                emit_struct(&mut out, &val_ty, &spec.value_fields, false);
            }
            other => bail!("[maps.{}] unsupported map_type `{other}`", spec.name),
        }
    }

    out.push_str(
        "/// Create every map declared in bpf.toml into the talc resource pool.\n\
         ///\n\
         /// Call after [`init`] and before network-stack bring-up.\n\
         /// Create maps keyed by [`ResourceId`] (`MAP_ID_*`).\n\
         /// AOT helpers resolve `&map` pointers via [`bind_aot_map_addrs`].\n",
    );

    emit_init_fn(&mut out, &map_specs)?;

    fs::write(out_dir.join("bpf_maps.rs"), out).context("write bpf_maps.rs")?;
    Ok(())
}

const EMPTY_INIT: &str = "\
pub async fn init_firmware_maps_via_builder(_rt: &mut crate::map::MapRt) -> Result<(), crate::map::Error> { Ok(()) }\n";

fn emit_init_fn(out: &mut String, map_specs: &[MapSpec]) -> Result<()> {
    out.push_str(
        "pub async fn init_firmware_maps_via_builder(rt: &mut MapRt) -> Result<(), Error> {\n",
    );

    for spec in map_specs {
        if spec.runtime {
            continue;
        }
        let type_stem = snake_to_pascal(&spec.name);
        let key_ty = format!("{type_stem}Key");
        let val_ty = format!("{type_stem}Value");
        let name = escape_rust_str(&spec.name);
        let id_const = format!("MAP_ID_{}", spec.name.to_ascii_uppercase());

        match spec.map_type.as_str() {
            "BPF_MAP_TYPE_HASH" => {
                out.push_str(&format!(
                    "    let _ = rt.push_builder(\n\
                            MapBuilder::hash()\n\
                            .with_name(\"{name}\")\n\
                            .with_key::<{key_ty}>()\n\
                            .with_value::<{val_ty}>()\n\
                            .with_capacity({})\n\
                    ).await?;\n",
                    spec.max_entries
                ));
            }
            "BPF_MAP_TYPE_ARRAY" => {
                out.push_str(&format!(
                    "    let _ = rt.push_builder(\n\
                            MapBuilder::array()\n\
                            .with_name(\"{name}\")\n\
                            .with_value::<{val_ty}>()\n\
                            .with_capacity({})\n\
                    ).await?;\n",
                    spec.max_entries
                ));
            }
            "BPF_MAP_TYPE_DEVMAP" => {
                out.push_str(&format!(
                    "    use crate::map::{{create_bpf_devmap, register_map_name, MapIdx}};\n\
                     create_bpf_devmap({id_const}, {}).await.map_err(|_| Error::Oom)?;\n\
                     let _ = register_map_name(\"{name}\", {id_const} as MapIdx);\n",
                    spec.max_entries
                ));
            }
            "BPF_MAP_TYPE_PROG_ARRAY" => {
                out.push_str(&format!(
                    "    use crate::map::{{create_bpf_prog_array, register_map_name, MapIdx}};\n\
                     create_bpf_prog_array({id_const}, {}).await.map_err(|_| Error::Oom)?;\n\
                     let _ = register_map_name(\"{name}\", {id_const} as MapIdx);\n",
                    spec.max_entries
                ));
            }
            "BPF_MAP_TYPE_RINGBUF" => {
                out.push_str(&format!(
                    "    let _ = rt.push_builder(\n\
                            MapBuilder::ringbuf()\n\
                            .with_name(\"{name}\")\n\
                            .with_capacity({})\n\
                    ).await?;\n",
                    spec.max_entries
                ));
            }
            "BPF_MAP_TYPE_XPOST_WDT_FEED" => {
                out.push_str(&format!(
                    "    use crate::map::{{create_bpf_wdt_feed, register_map_name, MapIdx}};\n\
                     create_bpf_wdt_feed({id_const}, {}).await.map_err(|_| Error::Oom)?;\n\
                     let _ = register_map_name(\"{name}\", {id_const} as MapIdx);\n",
                    spec.max_entries
                ));
            }
            other => bail!("[maps.{}] unsupported map_type `{other}`", spec.name),
        }
        let _ = id_const;
    }

    out.push_str("    Ok(())\n}\n");
    Ok(())
}

fn parse_fields(block: &str, map_name: &str, kind: &str) -> Result<Vec<(String, String)>> {
    let mut fields = Vec::new();
    for line in block.lines() {
        let line = line.trim();
        if line.is_empty() {
            continue;
        }
        let mut parts = line.split_whitespace();
        let ty = parts
            .next()
            .ok_or_else(|| anyhow::anyhow!("[maps.{map_name}] {kind}: bad field `{line}`"))?;
        let name = parts.next().ok_or_else(|| {
            anyhow::anyhow!("[maps.{map_name}] {kind}: missing field name in `{line}`")
        })?;
        if parts.next().is_some() {
            bail!("[maps.{map_name}] {kind}: unexpected tokens in `{line}`");
        }
        let rust_ty = match ty {
            "u8" | "u16" | "u32" | "u64" | "i8" | "i16" | "i32" | "i64" => ty.to_string(),
            other => bail!("[maps.{map_name}] {kind}: unsupported C type `{other}`"),
        };
        fields.push((rust_ty, name.to_string()));
    }
    if fields.is_empty() {
        bail!("[maps.{map_name}] {kind}: empty field list");
    }
    Ok(fields)
}

fn emit_struct(out: &mut String, name: &str, fields: &[(String, String)], is_key: bool) {
    out.push_str("#[repr(C)]\n");
    out.push_str("#[derive(Clone, Copy, Debug");
    if is_key {
        out.push_str(", PartialEq, Eq, Hash");
    }
    out.push_str(")]\n");
    out.push_str(&format!("pub struct {name} {{\n"));
    for (ty, field) in fields {
        out.push_str(&format!("    pub {field}: {ty},\n"));
    }
    out.push_str("}\n");
    let widths: Vec<String> = fields
        .iter()
        .map(|(ty, _)| {
            let (sz, _) = type_size_align(ty);
            sz.to_string()
        })
        .collect();
    if is_key {
        out.push_str(&format!("crate::impl_map_key!({name}, {});\n\n", widths.join(", ")));
    } else {
        out.push_str(&format!("crate::impl_map_value!({name}, {});\n\n", widths.join(", ")));
    }
}

fn type_size_align(ty: &str) -> (usize, usize) {
    match ty {
        "u8" | "i8" => (1, 1),
        "u16" | "i16" => (2, 2),
        "u32" | "i32" => (4, 4),
        "u64" | "i64" => (8, 8),
        other => panic!("unsupported C type `{other}`"),
    }
}

fn align_up(off: usize, align: usize) -> usize {
    (off + align - 1) & !(align - 1)
}

fn c_layout_size(fields: &[(String, String)]) -> usize {
    if fields.is_empty() {
        return 0;
    }
    let mut off = 0usize;
    let mut max_align = 1usize;
    for (ty, _) in fields {
        let (sz, al) = type_size_align(ty);
        off = align_up(off, al);
        off += sz;
        max_align = max_align.max(al);
    }
    align_up(off, max_align)
}
