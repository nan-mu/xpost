//! Parse optional `[[xdp.images]]` entries into boot-image metadata.

use std::fmt::Write as _;
use std::fs;
use std::path::Path;

use anyhow::{Context, Result, bail};

use crate::util::escape_rust_str;

/// Generate `xdp_bpf.rs`. An image declaration has a file path and its final
/// slot base: `[[xdp.images]] path = "assets/foo.bin" link_addr = 0x4038...`.
pub fn generate(board: &Path, out_dir: &Path) -> Result<()> {
    let text = fs::read_to_string(board.join("bpf.toml"))?;
    let root: toml::Table = text.parse().context("failed to parse bpf.toml")?;
    let images = root
        .get("xdp")
        .and_then(toml::Value::as_table)
        .and_then(|xdp| xdp.get("images"))
        .and_then(toml::Value::as_array);
    let mut out = String::from("// @generated by xtask from bpf.toml — do not edit.\n");
    let Some(images) = images else {
        out.push_str("pub(crate) static BOOT_IMAGES: &[BpfTomlImage] = &[];\n");
        fs::write(out_dir.join("xdp_bpf.rs"), out)?;
        return Ok(());
    };
    let mut entries = Vec::new();
    for (id, image) in images.iter().enumerate() {
        let image = image
            .as_table()
            .ok_or_else(|| anyhow::anyhow!("xdp.images[{id}] must be a table"))?;
        let path = image
            .get("path")
            .and_then(toml::Value::as_str)
            .ok_or_else(|| anyhow::anyhow!("xdp.images[{id}] missing path"))?;
        let link_addr = image
            .get("link_addr")
            .and_then(toml::Value::as_integer)
            .ok_or_else(|| anyhow::anyhow!("xdp.images[{id}] missing link_addr"))?;
        if link_addr < 0 {
            bail!("xdp.images[{id}].link_addr must be positive");
        }
        let path = board
            .join(path)
            .canonicalize()
            .with_context(|| format!("xdp.images[{id}] {}", path))?;
        writeln!(
            out,
            "static IMAGE_{id}: &[u8] = include_bytes!(\"{}\");",
            escape_rust_str(&path.display().to_string())
        )
        .unwrap();
        entries.push(format!(
            "    BpfTomlImage {{ table_id: {id}, link_addr: {link_addr:#x}, bytes: IMAGE_{id} }},"
        ));
    }
    out.push_str("pub(crate) static BOOT_IMAGES: &[BpfTomlImage] = &[\n");
    for entry in entries {
        writeln!(out, "{entry}").unwrap();
    }
    out.push_str("];\n");
    fs::write(out_dir.join("xdp_bpf.rs"), out).context("write xdp_bpf.rs")?;
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::generate;
    use std::fs;
    use std::path::PathBuf;

    fn fixture(name: &str) -> PathBuf {
        let path =
            std::env::temp_dir().join(format!("xpost-bpf-xdp-{name}-{}", std::process::id()));
        let _ = fs::remove_dir_all(&path);
        fs::create_dir_all(&path).unwrap();
        path
    }

    #[test]
    fn emits_empty_boot_list_without_xdp_images() {
        let board = fixture("empty");
        fs::write(board.join("bpf.toml"), "[maps]\n").unwrap();
        generate(&board, &board).unwrap();
        assert_eq!(
            fs::read_to_string(board.join("xdp_bpf.rs")).unwrap(),
            "// @generated by xtask from bpf.toml — do not edit.\npub(crate) static BOOT_IMAGES: &[BpfTomlImage] = &[];\n"
        );
        fs::remove_dir_all(board).unwrap();
    }

    #[test]
    fn emits_table_ids_and_static_image_slices() {
        let board = fixture("images");
        fs::write(board.join("image.bin"), [1_u8, 2, 3, 4]).unwrap();
        fs::write(
            board.join("bpf.toml"),
            "[[xdp.images]]\npath = \"image.bin\"\nlink_addr = 0x40380000\n",
        )
        .unwrap();
        generate(&board, &board).unwrap();
        let generated = fs::read_to_string(board.join("xdp_bpf.rs")).unwrap();
        assert!(generated.contains("static IMAGE_0: &[u8] = include_bytes!"));
        assert!(generated.contains("table_id: 0, link_addr: 0x40380000, bytes: IMAGE_0"));
        fs::remove_dir_all(board).unwrap();
    }
}
