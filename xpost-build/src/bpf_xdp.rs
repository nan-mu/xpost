//! Parse optional `[[xdp.images]]` → `boot_xdps` via [`XdpBuilder`].

use std::collections::BTreeMap;
use std::fmt::Write as _;
use std::fs;
use std::path::Path;

use anyhow::{Context, Result, bail};

use crate::util::escape_rust_str;

/// Generate `xdp_bpf.rs` with `boot_xdps(rt)` using [`::xpost::xdp::XdpBuilder`].
pub fn generate(board: &Path, out_dir: &Path) -> Result<()> {
    let text = fs::read_to_string(board.join("bpf.toml"))?;
    let root: toml::Table = text.parse().context("failed to parse bpf.toml")?;
    let images = root
        .get("xdp")
        .and_then(toml::Value::as_table)
        .and_then(|xdp| xdp.get("images"))
        .and_then(toml::Value::as_array);
    let mut out = String::from("// @generated by xpost-build from bpf.toml — do not edit.\n");
    let Some(images) = images else {
        out.push_str(EMPTY_BOOT);
        fs::write(out_dir.join("xdp_bpf.rs"), out)?;
        return Ok(());
    };

    let map_specs = parse_map_specs(&root)?;
    let all_map_names: Vec<String> = map_specs.keys().cloned().collect();

    for (id, image) in images.iter().enumerate() {
        let image = image
            .as_table()
            .ok_or_else(|| anyhow::anyhow!("xdp.images[{id}] must be a table"))?;
        let path = image
            .get("path")
            .and_then(toml::Value::as_str)
            .ok_or_else(|| anyhow::anyhow!("xdp.images[{id}] missing path"))?;
        let link_addr = image
            .get("link_addr")
            .and_then(toml::Value::as_integer)
            .ok_or_else(|| anyhow::anyhow!("xdp.images[{id}] missing link_addr"))?;
        if link_addr < 0 {
            bail!("xdp.images[{id}].link_addr must be positive");
        }
        let required_names: Vec<String> =
            if let Some(arr) = image.get("required_maps").and_then(|v| v.as_array()) {
                arr.iter()
                    .filter_map(|v| v.as_str().map(|s| s.to_string()))
                    .collect()
            } else {
                all_map_names.clone()
            };

        let path = board
            .join(path)
            .canonicalize()
            .with_context(|| format!("xdp.images[{id}] {}", path))?;
        writeln!(
            out,
            "static IMAGE_{id}: &[u8] = include_bytes!(\"{}\");",
            escape_rust_str(&path.display().to_string())
        )
        .unwrap();

        for (ri, map_name) in required_names.iter().enumerate() {
            let spec = map_specs.get(map_name).ok_or_else(|| {
                anyhow::anyhow!("xdp.images[{id}].required_maps: unknown map `{map_name}`")
            })?;
            if let Some(kl) = &spec.key_layout {
                writeln!(
                    out,
                    "static REQ_{id}_{ri}_KEY: &[u8] = &[{}];",
                    kl.iter()
                        .map(|b| b.to_string())
                        .collect::<Vec<_>>()
                        .join(", ")
                )
                .unwrap();
            }
            if let Some(vl) = &spec.value_layout {
                writeln!(
                    out,
                    "static REQ_{id}_{ri}_VAL: &[u8] = &[{}];",
                    vl.iter()
                        .map(|b| b.to_string())
                        .collect::<Vec<_>>()
                        .join(", ")
                )
                .unwrap();
            }
        }
    }

    out.push_str(
        "\n/// Register bpf.toml XDP images via [`::xpost::xdp::XdpBuilder`], then move to slots.\n\
         pub fn boot_xdps(rt: &mut ::xpost::xdp::XdpRt) -> Result<(), ::xpost::xdp::XdpError> {\n",
    );
    // Cap check: mirror former runtime guard.
    if images.len() > 8 {
        bail!("xdp.images: at most 8 images supported (got {})", images.len());
    }

    for (id, image) in images.iter().enumerate() {
        let image = image.as_table().unwrap();
        let link_addr = image.get("link_addr").and_then(|v| v.as_integer()).unwrap() as usize;
        let name = image
            .get("name")
            .and_then(toml::Value::as_str)
            .map(|s| s.to_string())
            .unwrap_or_else(|| format!("xdp_image_{id}"));
        let required_names: Vec<String> =
            if let Some(arr) = image.get("required_maps").and_then(|v| v.as_array()) {
                arr.iter()
                    .filter_map(|v| v.as_str().map(|s| s.to_string()))
                    .collect()
            } else {
                all_map_names.clone()
            };

        writeln!(
            out,
            r#"    rt.write_table_image({id}, IMAGE_{id})?;
    let slot = rt.slot_for({link_addr:#x})?;
    let mut b = ::xpost::xdp::XdpBuilder::from_existing({id}, IMAGE_{id}.len(), Some("{}"))
        .with_slot(slot)?
        .with_helper_address()
        .with_abi_version(0);"#,
            escape_rust_str(&name)
        )
        .unwrap();

        for (ri, map_name) in required_names.iter().enumerate() {
            let spec = map_specs.get(map_name).unwrap();
            let name = escape_rust_str(map_name);
            let cap = spec.len;
            let chain = match spec.kind {
                MapKind::Hash => {
                    format!(
                        r#"::xpost::xdp::XdpMaps::Builder(::xpost::map::MapBuilder::hash()
        .with_name("{name}")
        .with_key_layout(REQ_{id}_{ri}_KEY)
        .with_value_layout(REQ_{id}_{ri}_VAL)
        .with_capacity({cap}))"#
                    )
                }
                MapKind::Array => {
                    format!(
                        r#"::xpost::xdp::XdpMaps::Builder(::xpost::map::MapBuilder::array()
        .with_name("{name}")
        .with_value_layout(REQ_{id}_{ri}_VAL)
        .with_capacity({cap}))"#
                    )
                }
                MapKind::Ringbuf => {
                    format!(
                        r#"::xpost::xdp::XdpMaps::Builder(::xpost::map::MapBuilder::ringbuf()
        .with_name("{name}")
        .with_capacity({cap}))"#
                    )
                }
            };
            writeln!(out, "    b = b.with_maps([{chain}])?;").unwrap();
        }

        writeln!(
            out,
            r#"    let id = b.complete()?.build(rt)?;
    rt.r#move(id, ::xpost::xdp::XdpLocation::Slot {{ index: slot }})?;"#
        )
        .unwrap();
    }

    out.push_str("    Ok(())\n}\n");
    fs::write(out_dir.join("xdp_bpf.rs"), out).context("write xdp_bpf.rs")?;
    Ok(())
}

const EMPTY_BOOT: &str = "\
pub fn boot_xdps(_rt: &mut ::xpost::xdp::XdpRt) -> Result<(), ::xpost::xdp::XdpError> { Ok(()) }\n";

struct MapBootSpec {
    kind: MapKind,
    key_layout: Option<Vec<u8>>,
    value_layout: Option<Vec<u8>>,
    len: usize,
}

enum MapKind {
    Hash,
    Array,
    Ringbuf,
}

fn parse_map_specs(root: &toml::Table) -> Result<BTreeMap<String, MapBootSpec>> {
    let mut out = BTreeMap::new();
    let Some(maps) = root.get("maps").and_then(|v| v.as_table()) else {
        return Ok(out);
    };
    for (name, entry) in maps {
        let table = entry
            .as_table()
            .ok_or_else(|| anyhow::anyhow!("[maps.{name}] must be a table"))?;
        let map_type = table
            .get("map_type")
            .and_then(|v| v.as_str())
            .ok_or_else(|| anyhow::anyhow!("[maps.{name}] missing map_type"))?;
        let max_entries = table
            .get("max_entries")
            .and_then(|v| v.as_integer())
            .ok_or_else(|| anyhow::anyhow!("[maps.{name}] missing max_entries"))?
            as usize;

        let value_fields = table
            .get("value")
            .and_then(|v| v.as_str())
            .ok_or_else(|| anyhow::anyhow!("[maps.{name}] missing value"))?;
        let value_lens = field_lens(value_fields, name, "value")?;

        let (kind, key_layout, value_layout) = match map_type {
            "BPF_MAP_TYPE_HASH" => {
                let key = table
                    .get("key")
                    .and_then(|v| v.as_str())
                    .ok_or_else(|| anyhow::anyhow!("[maps.{name}] missing key"))?;
                let key_lens = field_lens(key, name, "key")?;
                (MapKind::Hash, Some(key_lens), Some(value_lens))
            }
            "BPF_MAP_TYPE_ARRAY" => (MapKind::Array, None, Some(value_lens)),
            "BPF_MAP_TYPE_RINGBUF" => (MapKind::Ringbuf, None, None),
            other => bail!("[maps.{name}] unsupported map_type `{other}` for xdp required_maps"),
        };

        out.insert(
            name.clone(),
            MapBootSpec {
                kind,
                key_layout,
                value_layout,
                len: max_entries,
            },
        );
    }
    Ok(out)
}

fn field_lens(block: &str, map_name: &str, kind: &str) -> Result<Vec<u8>> {
    let mut lenses = Vec::new();
    for line in block.lines() {
        let line = line.trim();
        if line.is_empty() {
            continue;
        }
        let mut parts = line.split_whitespace();
        let ty = parts
            .next()
            .ok_or_else(|| anyhow::anyhow!("[maps.{map_name}] {kind}: bad field `{line}`"))?;
        let _name = parts.next().ok_or_else(|| {
            anyhow::anyhow!("[maps.{map_name}] {kind}: missing field name in `{line}`")
        })?;
        if parts.next().is_some() {
            bail!("[maps.{map_name}] {kind}: unexpected tokens in `{line}`");
        }
        let width = match ty {
            "u8" | "i8" => 1u8,
            "u16" | "i16" => 2,
            "u32" | "i32" => 4,
            "u64" | "i64" => 8,
            other => bail!("[maps.{map_name}] {kind}: unsupported C type `{other}`"),
        };
        lenses.push(width);
    }
    if lenses.is_empty() {
        bail!("[maps.{map_name}] {kind}: empty field list");
    }
    Ok(lenses)
}
