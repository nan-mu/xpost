fn main() -> anyhow::Result<()> {
    println!("cargo:rerun-if-changed=../config/default.toml");
    println!("cargo:rerun-if-changed=../config/just_tx.toml");
    println!("cargo:rerun-if-changed=../config/just_drop.toml");
    println!("cargo:rerun-if-changed=src/generated/hot_a_bpf.rs");
    println!("cargo:rerun-if-changed=src/generated/tail_call_bpf.rs");

    let out_dir = PathBuf::from(env::var("OUT_DIR")?);
    generate_hot_a_assets(&out_dir)?;
    generate_tail_call_assets(&out_dir)?;
    generate_ddos_wl_assets(&out_dir)?;
    generate_ddos_rate_bl_assets(&out_dir)?;
    generate_xdp_echo_assets(&out_dir)?;
    generate_xdp_drop_assets(&out_dir)?;

    let cargo_metadata::Metadata { packages, .. } = cargo_metadata::MetadataCommand::new()
        .no_deps()
        .exec()
        .context("MetadataCommand::exec")?;
    let ebpf_package = packages
        .into_iter()
        .find(|cargo_metadata::Package { name, .. }| name.as_str() == "test-ebpf")
        .ok_or_else(|| anyhow!("test-ebpf package not found"))?;
    let cargo_metadata::Package {
        name,
        manifest_path,
        ..
    } = ebpf_package;

    // Host builds without bpfel toolchain can set TEST_SKIP_EBPF=1 (stub only; not for TR3000).
    if env::var_os("TEST_SKIP_EBPF").is_some() {
        let stub = out_dir.join("test_bpf");
        if stub.is_dir() {
            fs::remove_dir_all(&stub).with_context(|| format!("remove {}", stub.display()))?;
        }
        fs::write(&stub, b"\0").with_context(|| format!("write stub {}", stub.display()))?;
        println!(
            "cargo:warning=TEST_SKIP_EBPF set; wrote stub {}",
            stub.display()
        );
        return Ok(());
    }

    let ebpf_package = aya_build::Package {
        name: name.as_str(),
        root_dir: manifest_path
            .parent()
            .ok_or_else(|| anyhow!("no parent for {manifest_path}"))?
            .as_str(),
        ..Default::default()
    };
    aya_build::build_ebpf([ebpf_package], Toolchain::default())
}

fn parse_aot_addr(toml: &str) -> anyhow::Result<u64> {
    for line in toml.lines() {
        let t = line.trim();
        let Some(rest) = t.strip_prefix("aot_addr") else {
            continue;
        };
        let rest = rest.trim().trim_start_matches('=').trim();
        let hex = rest
            .strip_prefix("0x")
            .or_else(|| rest.strip_prefix("0X"))
            .unwrap_or(rest);
        return u64::from_str_radix(hex, 16).with_context(|| format!("parse aot_addr {rest}"));
    }
    anyhow::bail!("no aot_addr in bpf.toml")
}

fn generate_ddos_wl_assets(out_dir: &PathBuf) -> anyhow::Result<()> {
    let manifest_dir = PathBuf::from(env::var("CARGO_MANIFEST_DIR")?);
    let assets = manifest_dir.join("assets/ddos_wl");
    let bin = assets.join("esp32c3.bin");
    let toml = assets.join("bpf.toml");

    for p in [&bin, &toml] {
        println!("cargo:rerun-if-changed={}", p.display());
        if !p.is_file() {
            anyhow::bail!(
                "missing {}; pixi run build bpf/esp32c3 -i tests/xdp/ddos_wl.c then copy into test/assets/ddos_wl/",
                p.display()
            );
        }
    }

    let aot = parse_aot_addr(&fs::read_to_string(&toml)?)?;
    let rs = format!(
        "// Auto-generated by test/build.rs — do not edit.\n\
         \n\
         pub const BIN: &[u8] = include_bytes!(r#\"{}\"#);\n\
         pub const AOT_ADDR: u64 = {aot:#x};\n",
        bin.display(),
    );
    fs::write(out_dir.join("ddos_wl_assets.rs"), rs).context("write ddos_wl_assets.rs")?;
    Ok(())
}

fn parse_map_aot(toml: &str, map: &str) -> anyhow::Result<u64> {
    let header = format!("[maps.{map}]");
    let mut in_map = false;
    for line in toml.lines() {
        let t = line.trim();
        if t.starts_with('[') {
            in_map = t == header;
            continue;
        }
        if !in_map {
            continue;
        }
        let Some(rest) = t.strip_prefix("aot_addr") else {
            continue;
        };
        let rest = rest.trim().trim_start_matches('=').trim();
        let hex = rest
            .strip_prefix("0x")
            .or_else(|| rest.strip_prefix("0X"))
            .unwrap_or(rest);
        return u64::from_str_radix(hex, 16)
            .with_context(|| format!("parse {map} aot_addr {rest}"));
    }
    anyhow::bail!("no aot_addr for [maps.{map}]")
}

