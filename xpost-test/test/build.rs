use std::{env, fs, path::PathBuf};

use anyhow::{Context as _, anyhow};
use aya_build::Toolchain;

/// Embed pre-placed HOT_A AOT binaries from `assets/hot_a/{drop,pass}/`.
/// Someone else prepares `esp32c3.bin` (+ `bpf.toml`); this build does not copy or build them.
fn generate_hot_a_assets(out_dir: &PathBuf) -> anyhow::Result<()> {
    let manifest_dir = PathBuf::from(env::var("CARGO_MANIFEST_DIR")?);
    let assets = manifest_dir.join("assets/hot_a");
    let drop_bin = assets.join("drop/esp32c3.bin");
    let pass_bin = assets.join("pass/esp32c3.bin");

    for p in [&drop_bin, &pass_bin] {
        println!("cargo:rerun-if-changed={}", p.display());
        if !p.is_file() {
            anyhow::bail!(
                "missing {}; place esp32c3.bin under test/assets/hot_a/{{drop,pass}}/ (prepared externally)",
                p.display()
            );
        }
    }

    let rs = format!(
        "// Auto-generated by test/build.rs — do not edit.\n\
         \n\
         pub const DROP_BIN: &[u8] = include_bytes!(r#\"{}\"#);\n\
         pub const PASS_BIN: &[u8] = include_bytes!(r#\"{}\"#);\n",
        drop_bin.display(),
        pass_bin.display(),
    );
    fs::write(out_dir.join("hot_a_assets.rs"), rs).context("write hot_a_assets.rs")?;
    Ok(())
}

