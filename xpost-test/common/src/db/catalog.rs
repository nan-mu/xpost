//! Catalog facts read in the same transaction as Protocol V1 validation or DDL.

use super::ddl::Column;
use anyhow::Result;
use std::collections::BTreeMap;
use tokio_postgres::Transaction;

#[derive(Default)]
pub(super) struct Table {
    pub columns: Vec<Column>,
    pub objects: Vec<Object>,
    pub regular: bool,
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub(super) struct Object {
    pub kind: String,
    pub name: String,
    pub definition: String,
    pub referenced: String,
    pub check_columns: Vec<String>,
    pub active_write_trigger: bool,
}

pub(super) async fn tables(
    tx: &Transaction<'_>,
    names: &[String],
    prefix: &str,
) -> Result<BTreeMap<String, Table>> {
    let mut tables = BTreeMap::<String, Table>::new();
    let rows = tx.query(
        "SELECT c.relname::text, c.relkind = 'r' AND c.relpersistence = 'p'
                AND NOT c.relispartition AND NOT c.relrowsecurity
                AND NOT EXISTS (SELECT 1 FROM pg_inherits i WHERE c.oid IN (i.inhrelid,i.inhparent)),
                a.attname::text, format_type(a.atttypid, a.atttypmod), a.attnotnull
         FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace
         LEFT JOIN pg_attribute a ON a.attrelid = c.oid AND a.attnum > 0 AND NOT a.attisdropped
         WHERE n.nspname = 'release' AND c.relname::text = ANY($1)
         ORDER BY c.relname, a.attnum",
        &[&names],
    ).await?;
    for row in rows {
        let name: &str = row.get(0);
        let table = tables
            .entry(name.strip_prefix(prefix).unwrap_or(name).into())
            .or_default();
        table.regular = row.get(1);
        if let Some(name) = row.get::<_, Option<String>>(2) {
            table.columns.push(Column {
                name,
                data_type: row.get::<_, String>(3).replace(prefix, ""),
                not_null: row.get(4),
            });
        }
    }
    Ok(tables)
}

pub(super) async fn table_objects(
    tx: &Transaction<'_>,
    names: &[String],
    prefix: &str,
    tables: &mut BTreeMap<String, Table>,
) -> Result<()> {
    // Exclude the indexes backing constraints. Those definitions are part of
    // their constraints, and their index names can be generated by PostgreSQL.
    // Trigger event mask 28 covers INSERT (4), DELETE (8), and UPDATE (16).
    let rows = tx.query(
        "WITH relations AS (
           SELECT c.oid, c.relname::text AS name FROM pg_class c
           JOIN pg_namespace n ON n.oid = c.relnamespace
           WHERE n.nspname = 'release' AND c.relname::text = ANY($1)
         )
         SELECT r.name, c.contype::text, c.conname::text,
                pg_get_constraintdef(c.oid) || CASE WHEN c.convalidated THEN '' ELSE ' [unvalidated]' END,
                CASE WHEN n.nspname = 'release' THEN ref.relname::text ELSE '' END,
                ARRAY(SELECT a.attname::text FROM pg_attribute a
                      WHERE c.contype = 'c' AND a.attrelid = c.conrelid AND a.attnum = ANY(c.conkey)
                      ORDER BY a.attname COLLATE \"C\"), false
         FROM relations r JOIN pg_constraint c ON c.conrelid = r.oid
         LEFT JOIN pg_class ref ON ref.oid = c.confrelid
         LEFT JOIN pg_namespace n ON n.oid = ref.relnamespace
         UNION ALL
         SELECT r.name, 'index', c.relname::text,
                pg_get_indexdef(i.indexrelid) || CASE WHEN i.indisvalid THEN '' ELSE ' [invalid]' END,
                '', ARRAY[]::text[], false
         FROM relations r JOIN pg_index i ON i.indrelid = r.oid
         JOIN pg_class c ON c.oid = i.indexrelid
         WHERE NOT EXISTS (SELECT 1 FROM pg_constraint k
                           WHERE k.conindid = i.indexrelid AND k.conrelid = r.oid AND k.contype <> 'f')
         UNION ALL
         SELECT r.name, 'trigger', t.tgname::text,
                substr(pg_get_triggerdef(t.oid), length('CREATE TRIGGER ' || quote_ident(t.tgname)) + 2)
                  || ':' || t.tgenabled::text, '', ARRAY[]::text[],
                t.tgenabled IN ('O','A') AND (t.tgtype & 28) <> 0
         FROM relations r JOIN pg_trigger t ON t.tgrelid = r.oid WHERE NOT t.tgisinternal
         UNION ALL
         SELECT r.name, 'default', a.attname::text, pg_get_expr(d.adbin, d.adrelid), '', ARRAY[]::text[], false
         FROM relations r JOIN pg_attrdef d ON d.adrelid = r.oid
         JOIN pg_attribute a ON a.attrelid = r.oid AND a.attnum = d.adnum
         UNION ALL
         SELECT r.name, 'policy', p.polname::text, '', '', ARRAY[]::text[], false
         FROM relations r JOIN pg_policy p ON p.polrelid = r.oid
         UNION ALL
         SELECT r.name, 'rule', w.rulename::text, '', '', ARRAY[]::text[], false
         FROM relations r JOIN pg_rewrite w ON w.ev_class = r.oid
         UNION ALL
         SELECT r.name, 'owned sequence', s.relname::text, '', '', ARRAY[]::text[], false
         FROM relations r JOIN pg_depend d ON d.refobjid = r.oid
           AND d.refclassid = 'pg_class'::regclass AND d.classid = 'pg_class'::regclass
           AND d.deptype IN ('a','i') JOIN pg_class s ON s.oid = d.objid AND s.relkind = 'S'
         UNION ALL
         SELECT r.name, 'extended statistics', s.stxname::text, '', '', ARRAY[]::text[], false
         FROM relations r JOIN pg_statistic_ext s ON s.stxrelid = r.oid
         UNION ALL
         SELECT r.name, 'publication', p.pubname::text, '', '', ARRAY[]::text[], false
         FROM relations r JOIN pg_publication_rel pr ON pr.prrelid = r.oid
         JOIN pg_publication p ON p.oid = pr.prpubid
         ORDER BY 1, 2, 3",
        &[&names],
    ).await?;
    for row in rows {
        let name: &str = row.get(0);
        tables
            .get_mut(name.strip_prefix(prefix).unwrap_or(name))
            .expect("inventoried relation")
            .objects
            .push(Object {
                kind: row.get(1),
                name: row.get::<_, String>(2).replace(prefix, ""),
                definition: row.get::<_, String>(3).replace(prefix, ""),
                referenced: row.get::<_, String>(4).replace(prefix, ""),
                check_columns: row.get(5),
                active_write_trigger: row.get(6),
            });
    }
    Ok(())
}

pub(super) async fn globals(
    tx: &Transaction<'_>,
    names: &[String],
    prefix: &str,
) -> Result<BTreeMap<String, Vec<String>>> {
    let rows = tx.query(
        "SELECT p.proname::text, pg_get_functiondef(p.oid)
         FROM pg_proc p JOIN pg_namespace n ON n.oid = p.pronamespace
         WHERE n.nspname = 'release' AND p.proname::text = ANY($1) AND p.prokind = 'f'
         UNION ALL
         SELECT t.typname::text, 'domain:' || COALESCE(format_type(t.typbasetype, t.typtypmod),'')
             || ':' || t.typnotnull::text || ':' || COALESCE(t.typdefault,'')
             || ':' || COALESCE((SELECT string_agg(pg_get_constraintdef(c.oid), ',' ORDER BY pg_get_constraintdef(c.oid))
                                 FROM pg_constraint c WHERE c.contypid = t.oid), '')
         FROM pg_type t JOIN pg_namespace n ON n.oid = t.typnamespace
         WHERE n.nspname = 'release' AND t.typname::text = ANY($1) AND t.typtype = 'd'
         ORDER BY 1, 2",
        &[&names],
    ).await?;
    let mut result = BTreeMap::<String, Vec<String>>::new();
    for row in rows {
        let name: &str = row.get(0);
        result
            .entry(name.strip_prefix(prefix).unwrap_or(name).into())
            .or_default()
            .push(row.get::<_, String>(1).replace(prefix, ""));
    }
    Ok(result)
}
