//! Read pre-placed `bpf.toml` under test assets and emit Rust meta.
//!
//! Does **not** build AOT or copy binaries. Someone else must put
//! `esp32c3.bin` + `bpf.toml` into each asset dir beforehand.

use std::{fs, path::PathBuf};

use anyhow::{Context, Result, bail};
use clap::{Parser, Subcommand};
use quote::{format_ident, quote};
use serde::Deserialize;

#[derive(Parser)]
#[command(name = "xtask", about = "test helpers (read bpf.toml only)")]
struct Cli {
    #[command(subcommand)]
    cmd: Cmd,
}

#[derive(Subcommand)]
enum Cmd {
    /// Parse hot_a + tail_call asset bpf.toml → test/src/generated/*.rs.
    GenHotMeta,
}

fn repo_root() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR"))
        .parent()
        .expect("xtask parent")
        .to_path_buf()
}

#[derive(Debug, Deserialize)]
struct BpfToml {
    #[serde(default)]
    source: String,
    #[serde(default)]
    size: u64,
    #[serde(default)]
    xdp: XdpSection,
    #[serde(default)]
    maps: std::collections::BTreeMap<String, MapSection>,
}

#[derive(Debug, Default, Deserialize)]
struct XdpSection {
    #[serde(default)]
    size: u64,
}

#[derive(Debug, Deserialize)]
struct MapSection {
    #[serde(default)]
    map_type: String,
    #[serde(default)]
    max_entries: u32,
    #[serde(default)]
    aot_addr: u64,
}

fn read_variant(assets_root: &PathBuf, name: &str) -> Result<BpfToml> {
    let dir = assets_root.join(name);
    let toml_path = dir.join("bpf.toml");
    let bin_path = dir.join("esp32c3.bin");
    if !toml_path.is_file() {
        bail!(
            "missing {}; place bpf.toml (+ esp32c3.bin) under {}",
            toml_path.display(),
            dir.display()
        );
    }
    if !bin_path.is_file() {
        bail!(
            "missing {}; place esp32c3.bin next to bpf.toml in {}",
            bin_path.display(),
            dir.display()
        );
    }
    let text =
        fs::read_to_string(&toml_path).with_context(|| format!("read {}", toml_path.display()))?;
    toml::from_str(&text).with_context(|| format!("parse {}", toml_path.display()))
}

fn emit_variant(name: &str, bpf: &BpfToml) -> proc_macro2::TokenStream {
    let mod_name = format_ident!("{name}");
    let source = &bpf.source;
    let obj_size = bpf.size;
    let xdp_size = bpf.xdp.size;
    let maps = bpf.maps.iter().map(|(map_name, m)| {
        let map_type = &m.map_type;
        let max_entries = m.max_entries;
        let aot_addr = m.aot_addr;
        quote! {
            super::MapMeta {
                name: #map_name,
                map_type: #map_type,
                max_entries: #max_entries,
                aot_addr: #aot_addr,
            }
        }
    });
    quote! {
        pub mod #mod_name {
            pub const SOURCE: &str = #source;
            pub const OBJ_SIZE: u64 = #obj_size;
            pub const XDP_SIZE: u64 = #xdp_size;
            pub const MAPS: &[super::MapMeta] = &[
                #(#maps),*
            ];
        }
    }
}

fn write_meta_file(out_path: &PathBuf, header: &str, variants: &[(&str, BpfToml)]) -> Result<()> {
    let mods: Vec<_> = variants
        .iter()
        .map(|(name, bpf)| emit_variant(name, bpf))
        .collect();
    let file = quote! {
        #![allow(dead_code)]

        #[derive(Clone, Copy, Debug)]
        pub struct MapMeta {
            pub name: &'static str,
            pub map_type: &'static str,
            pub max_entries: u32,
            pub aot_addr: u64,
        }

        #(#mods)*
    };
    let pretty = prettyplease::unparse(&syn::parse2(file).context("parse generated TokenStream")?);
    let body = format!("//! {header}\n{pretty}");
    fs::write(out_path, body).with_context(|| format!("write {}", out_path.display()))?;
    println!("wrote {}", out_path.display());
    Ok(())
}

fn gen_hot_meta() -> Result<()> {
    let root = repo_root();
    let out_dir = root.join("test/src/generated");
    fs::create_dir_all(&out_dir).context("mkdir generated")?;

    let hot_a = root.join("test/assets/hot_a");
    let drop = read_variant(&hot_a, "drop")?;
    let pass = read_variant(&hot_a, "pass")?;
    write_meta_file(
        &out_dir.join("hot_a_bpf.rs"),
        "Auto-generated by `cargo xtask gen-hot-meta` — do not edit.\n//! Source: test/assets/hot_a/{drop,pass}/bpf.toml",
        &[("drop", drop), ("pass", pass)],
    )?;

    let tail = root.join("test/assets/tail_call");
    let a_tailcall = read_variant(&tail, "a_tailcall")?;
    let b_bounce = read_variant(&tail, "b_bounce")?;
    let b_drop = read_variant(&tail, "b_drop")?;
    write_meta_file(
        &out_dir.join("tail_call_bpf.rs"),
        "Auto-generated by `cargo xtask gen-hot-meta` — do not edit.\n//! Source: test/assets/tail_call/{a_tailcall,b_bounce,b_drop}/bpf.toml",
        &[
            ("a_tailcall", a_tailcall),
            ("b_bounce", b_bounce),
            ("b_drop", b_drop),
        ],
    )?;

    Ok(())
}

fn main() -> Result<()> {
    match Cli::parse().cmd {
        Cmd::GenHotMeta => gen_hot_meta(),
    }
}
