use std::env;
use std::fs;
use std::path::PathBuf;

fn main() {
    linker_be_nice();

    let manifest_dir = PathBuf::from(env::var("CARGO_MANIFEST_DIR").unwrap());
    let out_dir = PathBuf::from(env::var("OUT_DIR").unwrap());

    let cfg_path = manifest_dir.join("config.toml");
    let example_path = manifest_dir.join("config.example.toml");
    let src_path = if cfg_path.is_file() {
        cfg_path
    } else {
        example_path
    };

    println!("cargo:rerun-if-changed={}", src_path.display());
    println!("cargo:rerun-if-changed=config.toml");
    println!("cargo:rerun-if-changed=config.example.toml");

    let raw = fs::read_to_string(&src_path).expect("read config");
    let table: toml::Table = raw.parse().expect("parse config.toml");

    let wifi = table.get("wifi").and_then(|v| v.as_table()).expect("[wifi]");
    let probe = table.get("probe").and_then(|v| v.as_table()).expect("[probe]");
    let dut = table.get("dut").and_then(|v| v.as_table()).expect("[dut]");

    let ssid = wifi.get("ssid").and_then(|v| v.as_str()).expect("wifi.ssid");
    let password = wifi
        .get("password")
        .and_then(|v| v.as_str())
        .expect("wifi.password");
    let probe_ip = probe.get("ip").and_then(|v| v.as_str()).expect("probe.ip");
    let reply_port = probe
        .get("reply_port")
        .and_then(|v| v.as_integer())
        .expect("probe.reply_port") as u16;
    let ctrl_port = dut
        .get("ctrl_port")
        .and_then(|v| v.as_integer())
        .expect("dut.ctrl_port") as u16;

    let ip = parse_ipv4(probe_ip);

    let out_rs = format!(
        "// @generated by build.rs — do not edit\n\n\
         pub mod wifi {{\n\
             pub const SSID: &str = \"{}\";\n\
             pub const PASSWORD: &str = \"{}\";\n\
         }}\n\n\
         pub mod probe {{\n\
             pub const IP: [u8; 4] = [{}, {}, {}, {}];\n\
             pub const REPLY_PORT: u16 = {reply_port};\n\
         }}\n\n\
         pub mod dut {{\n\
             pub const CTRL_PORT: u16 = {ctrl_port};\n\
         }}\n",
        escape_rust_str(ssid),
        escape_rust_str(password),
        ip[0],
        ip[1],
        ip[2],
        ip[3],
    );

    fs::write(out_dir.join("fw_cfg_data.rs"), out_rs).expect("write fw_cfg_data.rs");

    println!("cargo:rustc-link-arg=-Tlinkall.x");
}

fn parse_ipv4(s: &str) -> [u8; 4] {
    let mut out = [0u8; 4];
    for (i, part) in s.split('.').enumerate() {
        assert!(i < 4, "invalid probe.ip: {s}");
        out[i] = part.parse().unwrap_or_else(|_| panic!("invalid probe.ip octet: {part}"));
    }
    out
}

fn escape_rust_str(s: &str) -> String {
    s.replace('\\', "\\\\").replace('\"', "\\\"")
}

fn linker_be_nice() {
    let args: Vec<String> = std::env::args().collect();
    if args.len() > 1 {
        let kind = &args[1];
        let what = &args[2];

        match kind.as_str() {
            "undefined-symbol" => match what.as_str() {
                what if what.starts_with("_defmt_") => {
                    eprintln!();
                    eprintln!(
                        "💡 `defmt` not found - make sure `defmt.x` is added as a linker script and you have included `use defmt_rtt as _;`"
                    );
                    eprintln!();
                }
                "_stack_start" => {
                    eprintln!();
                    eprintln!("💡 Is the linker script `linkall.x` missing?");
                    eprintln!();
                }
                what if what.starts_with("esp_rtos_") => {
                    eprintln!();
                    eprintln!(
                        "💡 `esp-radio` has no scheduler enabled. Make sure you have initialized `esp-rtos` or provided an external scheduler."
                    );
                    eprintln!();
                }
                "embedded_test_linker_file_not_added_to_rustflags" => {
                    eprintln!();
                    eprintln!(
                        "💡 `embedded-test` not found - make sure `embedded-test.x` is added as a linker script for tests"
                    );
                    eprintln!();
                }
                "free"
                | "malloc"
                | "calloc"
                | "get_free_internal_heap_size"
                | "malloc_internal"
                | "realloc_internal"
                | "calloc_internal"
                | "free_internal" => {
                    eprintln!();
                    eprintln!(
                        "💡 Did you forget the `esp-alloc` dependency or didn't enable the `compat` feature on it?"
                    );
                    eprintln!();
                }
                _ => (),
            },
            _ => {
                std::process::exit(1);
            }
        }

        std::process::exit(0);
    }

    println!(
        "cargo:rustc-link-arg=--error-handling-script={}",
        std::env::current_exe().unwrap().display()
    );
}
